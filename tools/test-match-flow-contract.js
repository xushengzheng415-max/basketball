'use strict';
const assert=require('assert'),fs=require('fs');
const flow=fs.readFileSync('cloudfunctions/sxMatchFlow/index.js','utf8');
const detail=fs.readFileSync('native-dist/pages/tournament-detail/index.js','utf8');
const prep=fs.readFileSync('native-dist/pages/match-preparation/index.js','utf8');
const coach=fs.readFileSync('native-dist/pages/match-coach-live/index.js','utf8');
const tactics=fs.readFileSync('native-dist/pages/match-tactics/index.js','utf8');
const board=fs.readFileSync('native-dist/pages/scorer-board/index.js','utf8');
const home=fs.readFileSync('native-dist/pages/home/index.js','utf8');
const tournament=fs.readFileSync('cloudfunctions/sxTournamentLeague/index.js','utf8');
assert.ok(flow.includes("x.role!=='home_coach'"),'只有主队负责人可指派裁判');
assert.ok(flow.includes('双方负责人不能担任本场裁判'),'双方负责人必须排除');
assert.ok(flow.includes("mode:'skipped'")&&flow.includes("mode:'submitted'"),'名单与跳过模式必须并存');
assert.ok(flow.includes("x.role!=='referee'")&&flow.includes('仅已接受任务的裁判可开赛'),'开赛必须由裁判执行');
assert.ok(flow.includes("action==='substitution'")&&flow.includes('playingSeconds'),'换人必须累计上场时间');
assert.ok(flow.includes('approved_waiting_execution')&&flow.includes("action==='linkTimeout'"),'暂停申请需等待裁判手动执行');
assert.ok(flow.includes('sx_team_tactic_library'),'战术需保存到球队私有战术库');
assert.ok(detail.includes('/pages/match-preparation/index?matchId='),'对阵卡应进入准备页');
assert.ok(/action\s*:\s*["']start["']/.test(prep)&&/["']requestTimeout["']/.test(coach),'准备与教练操作页应接入云端');
assert.ok(tactics.includes("action:'save'")&&board.includes('reviewCoachTimeout'),'战术保存和裁判暂停提示必须存在');
assert.ok(flow.includes("action==='restart'")&&flow.includes("type:'match_restart'"),'比赛重开必须清理本场数据并保留审计记录');
assert.ok(/action\s*:\s*["']restart["']/.test(prep)&&prep.includes('已恢复到赛前准备'),'比赛准备页必须提供正式重开入口');
assert.ok(flow.includes("await task(u,next,'referee','official',false)")&&flow.includes("'match_completed'"),'外部裁判接受后应保留首页任务，完赛后自动关闭');
assert.ok(tournament.includes("task.type === 'match_referee_accept' || task.unread !== false"),'裁判任务已读后仍应保留在工作台');
assert.ok(tournament.includes('refereePreparations')&&tournament.includes("type: 'match_referee_accept'"),'工作台应自动补回历史缺失的裁判任务');
assert.ok(home.includes("refereeLive ? '进入裁判台'")&&home.includes('/pages/scorer-board/index?boardOnly=1&matchId='),'比赛进行中的裁判任务应直接返回计分台');
assert.ok(board.includes('buildOfficialRoster')&&board.includes('!restored && !this.liveMatchId'),'正式裁判台必须按matchId加载本场数据，不能复用快速比赛缓存');
assert.ok(board.includes('context.homeRoster')&&board.includes('context.awayRoster'),'正式裁判台必须读取双方本场名单');
console.log('match flow contract tests passed');
