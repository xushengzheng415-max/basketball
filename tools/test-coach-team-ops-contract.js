assert.ok(api.includes('scoreConsistent'),'赛后汇总必须校验球员得分与官方比分');
assert.ok(page.includes("setWorkMode")&&page.includes("createInvite")&&page.includes("inviteExistingCoach")&&page.includes("recordEvent")&&page.includes("submitSummary"),'工作台应覆盖赛前、机构/临时助教邀请、赛中与赛后闭环');
