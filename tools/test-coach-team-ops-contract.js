'use strict';
const assert=require('assert'),fs=require('fs');
const api=fs.readFileSync('cloudfunctions/sxCoachTeamOps/index.js','utf8');
const page=fs.readFileSync('native-dist/pages/match-coach-workspace/index.js','utf8');
const prep=fs.readFileSync('native-dist/pages/match-preparation/index.js','utf8');
const live=fs.readFileSync('native-dist/pages/match-coach-live/index.js','utf8');
const home=fs.readFileSync('native-dist/pages/home/index.js','utf8');
assert.ok(api.includes('双方需先完成本场名单选择'),'双方名单完成后才开放教练分工');
assert.ok(api.includes('每队最多邀请5名助教'),'每队助教上限应为5人');
assert.ok(api.includes('该数据不在你的分工范围'),'助教必须受任务范围约束');
assert.ok(api.includes('比赛开始后分工已锁定'),'开赛后分工必须锁定');
assert.ok(api.includes('existingCoachCandidates')&&api.includes('match_assistant_invite'),'应复用机构成员关系邀请已有教练并生成工作台待办');
assert.ok(api.includes('该助教邀请仅限指定教练接受'),'定向机构教练邀请不得被其他账号认领');
