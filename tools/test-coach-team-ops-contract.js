assert.ok(prep.includes('showCoachWorkspace')&&prep.includes('goCoachWorkspace'),'比赛准备页应开放教练团队入口');
assert.ok(live.includes('openWorkspace'),'比赛中教练端应可进入协作工作台');
assert.ok(home.includes("task.type === 'match_assistant_invite'")&&home.includes('/pages/match-coach-workspace/index?assistantInvite='),'机构教练助教邀请应从首页任务直达接受页');
console.log('coach team operations contract tests passed');
